"""관문 0 — 검색보다 **먼저** 갈라야 하는 질문을 걸러낸다.

실측이 이 층의 필요를 만들었다. 검색을 먼저 태웠더니 세 문항이 엉뚱한 데로 갔다.
  A04 "입금했는데 아직도 입금대기라고 떠요"  → 문서를 보고 답해버림 (사람에게 갔어야)
  T01 "이 머그컵 지금 재고 있어요?"          → 문서가 없어 사람 연결 (조회로 갔어야)
  T02 "우편번호 63000인데 배송비 얼마?"      → 〃

**개별 처리 요구와 실시간 조회는 문서로 답할 수 있는 종류가 아니다.** 검색에 태우는 것
자체가 잘못이다. 검색은 "가장 비슷한 것"을 늘 내밀기 때문에, 태우는 순간 답이 있는 것처럼
보이게 된다.

🚨 **키워드를 모델보다 앞에 두는 이유**: 모델은 오판한다. 실측에서 8B는 T03을 제대로
   막았는데 14B는 일반론으로 답해버렸다(큰 모델일수록 과신한다). 키워드는 무식하지만
   **틀리는 방식이 예측 가능**하다. 최소 방어선은 사람이 읽을 수 있는 규칙이어야 한다.
   모델은 이 뒤에서 나머지를 판단한다 — 둘은 대체가 아니라 겹침이다.

규칙은 **좁게** 잡는다. 넓게 잡으면 "카드 되나요?" 같은 일반 규정 질문까지 사람에게
넘어가 챗봇이 무용해진다. 확실한 것만 여기서 끝내고 나머지는 뒤로 넘긴다.
"""

import re
from typing import Literal

Route = Literal["escalate", "lookup", "search"]

# ── 개별 처리 요구 ──────────────────────────────────────────────
# "규정을 묻는 것"과 "내 건을 처리해 달라는 것"을 가르는 표현만 넣는다.
#
# 🚨 "입금했는데"를 넣지 않는 이유: A03("친구 이름으로 입금했는데 괜찮아요?")은
#    규정 질문이고 A04("입금했는데 아직도…")는 개별 문제다. 둘을 가르는 것은
#    '입금했는데'가 아니라 **'아직도'** 다. 겹치는 말로 규칙을 만들면 오탐이 난다.
_ESCALATE = re.compile(
    r"해\s?주세요|해줘|해주실|해주시"          # 처리 요구
    r"|아직도|아직\s?안|안\s?왔|안왔"          # 안 됐다는 호소
    r"|안\s?들어왔|안들어왔"
    r"|잘못"                                   # 잘못 썼는데 / 잘못 보냈어요
    r"|두\s?번|중복"                           # 이중 결제
    r"|파손|깨졌|불량|하자"                    # 상품 문제 — 판매자 귀책 판단이 필요
)

# ── 실시간 조회 ────────────────────────────────────────────────
# 문서에는 절대 없는 값들. 색인은 늘 과거이므로 여기서 답하면 안 된다.
_LOOKUP = re.compile(
    r"재고|품절|남았|남아\s?있"                # 재고
    r"|어디쯤|어디까지|배송\s?조회|송장|운송장"  # 배송 추적
)
# 우편번호 5자리 — 도서산간·배송비는 지역이 정해져야 계산된다
_POSTAL = re.compile(r"(?<!\d)\d{5}(?!\d)")


def route(question: str) -> Route:
    """검색 앞에서 한 번 거른다.

    순서가 곧 우선순위다. **처리 요구가 조회보다 앞선다** — "제 주문 취소해 주세요"는
    조회가 아니라 사람이 할 일이고, 안전한 쪽으로 기울이는 것이 이 층의 목적이다.
    """
    if _ESCALATE.search(question):
        return "escalate"
    if _LOOKUP.search(question) or _POSTAL.search(question):
        return "lookup"
    return "search"
